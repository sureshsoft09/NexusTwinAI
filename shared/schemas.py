"""Enterprise Pydantic schemas for NexusTwin AI.

Standardized data transfer contracts across ADK Multi-Agent swarms,
FastMCP Streamable HTTP microservices, FastAPI Agent Bridge, and BigQuery Lakehouse.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class GateStatus(str, Enum):
    APPROVED = "APPROVED"
    REFERRED_TO_HUMAN = "REFERRED_TO_HUMAN"
    REJECTED = "REJECTED"


class MarketSignalEvent(BaseModel):
    """Inbound telemetry signal from POS Scanner, Weather API Forecast, or Social Media Monitor."""
    event_id: str = Field(..., description="Unique event identifier, e.g. evt_tx_9921")
    store_id: str = Field(..., description="Retail store identifier, e.g. STORE-DAL-04")
    sku_id: str = Field(..., description="Universal product SKU, e.g. SKU-4089-HYDRATE")
    observed_velocity: float = Field(..., description="Real-time or projected sales velocity (units/hour)")
    baseline_velocity: float = Field(..., description="Baseline 30-day velocity (units/hour)")
    current_store_stock: int = Field(..., description="Units on shelf and store backroom")
    signal_source: str = Field(
        default="POS_SCANNER",
        description="Trigger source: POS_SCANNER | WEATHER_FORECAST_25D | SOCIAL_MEDIA_MONITOR",
    )
    forecast_horizon_days: int = Field(
        default=0,
        description="0 for real-time POS/Social spikes; 25 for 25-day Weather API prediction",
    )
    requested_units_override: Optional[int] = Field(
        default=None,
        description="Optional override for replenishment units needed",
    )
    context_notes: Optional[str] = Field(None, description="External context, e.g. Weather / local events / social buzz")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class MarketSignalContext(BaseModel):
    """Enriched market sensing context generated by the Sensing Agent."""
    event_id: str
    store_id: str
    sku_id: str
    signal_source: str = "POS_SCANNER"
    forecast_horizon_days: int = 0
    velocity_spike_ratio: float
    projected_stockout_hours: float
    root_cause_explanation: str
    external_factors: Dict[str, Any] = Field(default_factory=dict)
    confidence_score: float = Field(..., ge=0.0, le=1.0)


class LogisticsOption(BaseModel):
    """Logistics route and freight quote from logistics_rates_mcp."""
    carrier_name: str
    freight_mode: str  # e.g., "LATERAL_GROUND_TRANSFER", "FMCG_DIRECT_PO_FREIGHT", "EXPEDITED_AIR_FREIGHT"
    origin_dc: str
    destination_store: str
    transit_hours: float
    freight_cost: float
    eta_iso: str
    service_level: str


class ReplenishmentProposal(BaseModel):
    """Autonomous replenishment proposal synthesized by replenishment_agent."""
    proposal_id: str
    event_id: str
    sku_id: str
    target_store: str
    selected_donor_dc: str
    order_type: str = "STO_FROM_DC"  # "STO_FROM_DC" or "PO_TO_FMCG"
    units_to_transfer: int
    donor_current_stock: int
    donor_safety_stock: int
    donor_atp_surplus: int
    dc_shortage_escalated_to_fmcg: bool = False
    fmcg_vendor_id: Optional[str] = None
    fmcg_po_merchandise_cost: float = 0.0
    unit_retail_price: float = 14.99
    unit_gross_margin: float = 6.20
    projected_protected_revenue: float
    selected_logistics: Optional[LogisticsOption] = None


class GateRuleResult(BaseModel):
    """Evaluation result for an individual Feasibility Gate rule."""
    rule_name: str
    passed: bool
    threshold: Any
    actual_value: Any
    message: str


class GateEvaluationResult(BaseModel):
    """Deterministic 4-Rule Feasibility Gate evaluation output."""
    event_id: str
    gate_status: GateStatus
    passed: bool
    requires_human_approval: bool
    rejection_reason: Optional[str] = None
    rules_evaluated: List[GateRuleResult]
    evaluated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ApprovalDecisionRequest(BaseModel):
    """Human approval submission for transfers/POs exceeding $1,000 autonomy threshold."""
    event_id: str
    approved: bool
    approver_name: str = "VP of Supply Chain Operations"
    approver_email: str = "director.ops@enterprise-fmcg.com"
    comments: Optional[str] = "Approved via React Control Tower"
    signed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ReplenishmentDecisionManifest(BaseModel):
    """Comprehensive decision payload dispatched to ERP, BigQuery Lakehouse, and UI."""
    event_id: str
    sku_id: str
    target_store: str
    selected_donor_dc: str
    order_type: str = "STO_FROM_DC"  # "STO_FROM_DC" or "PO_TO_FMCG"
    signal_source: str = "POS_SCANNER"
    forecast_horizon_days: int = 0
    units_transferred: int
    freight_mode: str
    carrier_name: str
    estimated_freight_cost: float
    fmcg_po_merchandise_cost: float = 0.0
    total_financial_commitment: float = 0.0
    root_cause_explanation: str
    gate_status: GateStatus
    requires_human_approval: bool
    sap_transfer_order_id: Optional[str] = None
    fmcg_purchase_order_id: Optional[str] = None
    agent_engine_resource_id: Optional[str] = None
    vertex_session_id: Optional[str] = None
    remote_executed: bool = False
    agent_response_text: Optional[str] = None
    step_events: List[Dict[str, Any]] = Field(default_factory=list)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class AuditLedgerEntry(BaseModel):
    """BigQuery Operational Lakehouse audit trail row."""
    event_id: str
    timestamp: datetime
    signal_source: str
    store_id: str
    sku_id: str
    observed_velocity: float
    root_cause_explanation: str
    selected_donor_dc: str
    order_type: str = "STO_FROM_DC"
    units_transferred: int
    freight_mode: str
    carrier_name: str
    estimated_freight_cost: float
    gate_status: str
    requires_human_approval: bool
    approver_name: Optional[str] = None
    sap_transfer_order_id: Optional[str] = None
